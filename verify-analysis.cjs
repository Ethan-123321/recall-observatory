const assert=require('node:assert/strict');
const fs=require('node:fs');
const A=require('./dist/analysis.js');
const allRows=JSON.parse(fs.readFileSync(__dirname+'/dataset/recalls.json','utf8'));
const rows=allRows.filter(r=>r.retrieved_date==='2026-10-16');
assert.equal(allRows.length,211);
assert.equal(rows.length,108);
assert.equal(A.filter(rows,{category:'玩具'}).length,25);
assert.equal(A.filter(rows,{category:'玩具',risk:'窒息/误吞'}).length,13);
assert.equal(A.filter(rows,{scope:'按型号与生产日期界定'}).length,20);
assert.equal(A.filter(rows,{scope:'范围细节需补充确认'}).length,10);
assert.equal(A.filter(rows,{from:'2026-01-01',to:'2025-01-01'}).length,0);
assert.equal(A.filter(rows,{query:'not-a-product-123'}).length,0);
assert.equal(A.filter(rows,{query:'sg107max'}).length,1);
assert.equal(A.counts(rows,'category').reduce((s,x)=>s+x[1],0),108);
assert.equal(A.counts(rows,'risk_tags').reduce((s,x)=>s+x[1],0),124);
assert.equal(A.months(rows).length,15);
assert.equal(A.filter(rows,{month:'2025-12'}).length,0);
const toy=A.filter(rows,{category:'玩具'});
assert.equal(new Map(A.units(toy)).get('只'),8420);
assert.equal(new Map(A.units(toy)).get('个'),1120);
assert.equal(A.csv(toy).split('\r\n').length,26);
assert.ok(A.csv([{title:'=HYPERLINK("x")'}]).includes("'=HYPERLINK"));
const published=fs.readFileSync(__dirname+'/dist/dataset.js','utf8');
assert.deepEqual(JSON.parse(published.slice('const recallDataset = '.length).trim().replace(/;$/,'')),allRows);
console.log('PASS: filters, multi-risk counts, dates, units, CSV escaping and published dataset consistency.');

assert.equal(A.months(allRows).length,21);
assert.equal(A.counts(allRows,'category').length,18);
assert.equal(A.filter(allRows,{category:'玩具'}).length,44);
const fixture=[{category:'甲',risk_tags:['火','电']},{category:'甲',risk_tags:['电']}];
assert.deepEqual(A.matrix(fixture,['甲','乙'],['火','电'],true),[[0,0,50,1,2],[1,0,100,2,2],[0,1,0,0,0],[1,1,0,0,0]]);
assert.equal(A.counts(allRows,'category').reduce((s,x)=>s+x[1],0),211);
console.log('PASS: expanded dataset, percentage denominators, zero sample and multi-label matrix.');
